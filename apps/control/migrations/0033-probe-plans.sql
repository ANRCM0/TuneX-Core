-- Bounded plan intent and historical decisions, never execution permits.
CREATE TABLE probe_plan_scopes (
 scope_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 rows_expired BIGINT UNSIGNED NOT NULL DEFAULT 0,
 rows_evicted BIGINT UNSIGNED NOT NULL DEFAULT 0,
 decisions_evicted BIGINT UNSIGNED NOT NULL DEFAULT 0,
 CHECK(rows_expired<=9007199254740991 AND rows_evicted<=9007199254740991 AND decisions_evicted<=9007199254740991)
);
CREATE TABLE probe_plans (
 scope_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 plan_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 created_by VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 created_at BIGINT UNSIGNED NOT NULL,
 config JSON NOT NULL,
 config_digest CHAR(71) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 origin_binding JSON NOT NULL,
 forward_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 mode ENUM('manual','scheduled') NOT NULL,
 expires_at BIGINT UNSIGNED NOT NULL,
 revision BIGINT UNSIGNED NOT NULL,
 state ENUM('active','completed','cancelled','expired','suspended') NOT NULL,
 decision_count INT UNSIGNED NOT NULL,
 accepted_count INT UNSIGNED NOT NULL,
 next_run_at BIGINT UNSIGNED NOT NULL,
 updated_at BIGINT UNSIGNED NOT NULL,
 cancelled_by VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL,
 cancelled_at BIGINT UNSIGNED NULL,
 last_code VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
 recovery_suspended BOOLEAN NOT NULL DEFAULT FALSE,
 PRIMARY KEY(scope_id,plan_id),
 INDEX probe_plan_window(scope_id,created_at,plan_id),
 INDEX probe_plan_due(state,mode,next_run_at,scope_id,plan_id),
 FOREIGN KEY(scope_id) REFERENCES probe_plan_scopes(scope_id),
 CHECK(JSON_TYPE(config)='OBJECT' AND OCTET_LENGTH(config)<=2048),
 CHECK(JSON_TYPE(origin_binding)='OBJECT' AND OCTET_LENGTH(origin_binding)<=2048),
 CHECK(JSON_TYPE(JSON_EXTRACT(config,'$.forwardId'))='STRING' AND JSON_EXTRACT(config,'$.forwardId') IS NOT NULL),
 CHECK(CAST(JSON_UNQUOTE(JSON_EXTRACT(config,'$.forwardId')) AS BINARY)=CAST(forward_id AS BINARY)),
 CHECK(JSON_TYPE(JSON_EXTRACT(config,'$.mode'))='STRING' AND JSON_EXTRACT(config,'$.mode') IS NOT NULL),
 CHECK(CAST(JSON_UNQUOTE(JSON_EXTRACT(config,'$.mode')) AS BINARY)=CAST(mode AS BINARY)),
 CHECK(JSON_TYPE(JSON_EXTRACT(config,'$.expiresAt'))='INTEGER' AND JSON_EXTRACT(config,'$.expiresAt') IS NOT NULL),
 CHECK(JSON_EXTRACT(config,'$.expiresAt')=expires_at),
 CHECK(JSON_TYPE(JSON_EXTRACT(config,'$.maxRuns'))='INTEGER' AND JSON_EXTRACT(config,'$.maxRuns') IS NOT NULL),
 CHECK(JSON_EXTRACT(config,'$.maxRuns') BETWEEN 1 AND 16 AND decision_count<=JSON_EXTRACT(config,'$.maxRuns')),
 CHECK(created_at<=253402300799999 AND expires_at>created_at AND expires_at<=created_at+3600000),
 CHECK(revision BETWEEN 1 AND 9007199254740991),
 CHECK(decision_count<=16 AND accepted_count<=decision_count),
 CHECK(state<>'active' OR decision_count<JSON_EXTRACT(config,'$.maxRuns')),
 CHECK(state<>'completed' OR decision_count=JSON_EXTRACT(config,'$.maxRuns')),
 CHECK(state<>'expired' OR updated_at>=expires_at),
 CHECK(updated_at BETWEEN created_at AND 253402300799999 AND next_run_at<=253402300799999),
 CHECK((state='active' AND mode='scheduled' AND next_run_at>0) OR ((state<>'active' OR mode='manual') AND next_run_at=0)),
 CHECK((cancelled_by IS NULL AND cancelled_at IS NULL AND state<>'cancelled') OR (cancelled_by IS NOT NULL AND cancelled_at BETWEEN created_at AND updated_at AND state='cancelled')),
 CHECK(recovery_suspended IN (0,1)),
 CHECK(state<>'active' OR recovery_suspended=FALSE)
);
CREATE TABLE probe_plan_decisions (
 scope_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 plan_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 position INT UNSIGNED NOT NULL,
 actor_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 source ENUM('manual','scheduled') NOT NULL,
 decided_at BIGINT UNSIGNED NOT NULL,
 outcome JSON NOT NULL,
 PRIMARY KEY(scope_id,plan_id,position),
 FOREIGN KEY(scope_id,plan_id) REFERENCES probe_plans(scope_id,plan_id) ON DELETE CASCADE,
 CHECK(position BETWEEN 1 AND 16),
 CHECK(decided_at<=253402300799999),
 CHECK(JSON_TYPE(outcome)='OBJECT' AND OCTET_LENGTH(outcome)<=2048)
);
