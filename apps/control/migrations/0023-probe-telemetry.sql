-- Independent cumulative Probe observations, never permit issuance or execution authority.
-- Logical JSON budget: 4096 points/Node * (4096 point + 2048 exporter) = 24 MiB/Node.
-- SQL JSON representation, row metadata and indexes add overhead: this is not a whole-DB disk cap.
CREATE TABLE probe_telemetry_heads (
 node_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 scope_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 session_epoch BIGINT UNSIGNED NOT NULL,
 boot_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 sample_epoch CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 last_sequence BIGINT UNSIGNED NOT NULL DEFAULT 0,
 last_uptime_ms BIGINT UNSIGNED NOT NULL DEFAULT 0,
 last_digest CHAR(71) CHARACTER SET ascii COLLATE ascii_bin NULL,
 last_received_at BIGINT UNSIGNED NOT NULL DEFAULT 0,
 last_captured_at BIGINT UNSIGNED NOT NULL DEFAULT 0,
 dropped_samples VARCHAR(20) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT '0',
 accepted_points TINYINT UNSIGNED NOT NULL DEFAULT 0,
 rejected_points TINYINT UNSIGNED NOT NULL DEFAULT 0,
 FOREIGN KEY(node_id) REFERENCES nodes(id),
 FOREIGN KEY(scope_id) REFERENCES scopes(id),
 CHECK(session_epoch BETWEEN 1 AND 9007199254740991),
 CHECK(last_sequence<=9007199254740991),
 CHECK(last_uptime_ms<=9007199254740991),
 CHECK(last_received_at<=8640000000000000),
 CHECK(last_captured_at<=8640000000000000),
 CHECK(accepted_points<=32 AND rejected_points<=32 AND accepted_points+rejected_points<=32),
 CHECK(dropped_samples REGEXP '^(0|[1-9][0-9]{0,19})$'),
 CHECK(CAST(dropped_samples AS DECIMAL(20,0))<=18446744073709551615)
);
CREATE TABLE probe_telemetry_points (
 node_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 scope_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 forward_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 session_epoch BIGINT UNSIGNED NOT NULL,
 boot_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 sample_epoch CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 sequence BIGINT UNSIGNED NOT NULL,
 item_index TINYINT UNSIGNED NOT NULL,
 received_at BIGINT UNSIGNED NOT NULL,
 captured_at BIGINT UNSIGNED NOT NULL,
 sample_captured_at BIGINT UNSIGNED NOT NULL,
 uptime_ms BIGINT UNSIGNED NOT NULL,
 identity_digest CHAR(71) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 counter_epoch CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
 body JSON NOT NULL,
 exporter JSON NOT NULL,
 digest CHAR(71) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 mapping_source VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 published_until BIGINT UNSIGNED NOT NULL,
 probe_instance VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 instance_until BIGINT UNSIGNED NULL,
 recovery_suspended BOOLEAN NOT NULL DEFAULT FALSE,
 PRIMARY KEY(node_id,sample_epoch,sequence,item_index),
 INDEX probe_telemetry_node_time(node_id,received_at,sample_epoch,sequence,item_index),
 INDEX probe_telemetry_retention(received_at,node_id),
 INDEX probe_telemetry_forward_time(scope_id,forward_id,received_at,node_id,sample_epoch,sequence,item_index),
 INDEX probe_telemetry_instance_time(scope_id,forward_id,identity_digest,counter_epoch,received_at,node_id,sample_epoch,sequence,item_index),
 FOREIGN KEY(node_id) REFERENCES nodes(id),
 FOREIGN KEY(scope_id) REFERENCES scopes(id),
 FOREIGN KEY(forward_id) REFERENCES forwards(id),
 CHECK(session_epoch BETWEEN 1 AND 9007199254740991),
 CHECK(sequence BETWEEN 1 AND 9007199254740991),
 CHECK(item_index<=31),
 CHECK(received_at<=8640000000000000),
 CHECK(captured_at<=8640000000000000),
 CHECK(sample_captured_at<=8640000000000000),
 CHECK(uptime_ms<=9007199254740991),
 CHECK(published_until<=8640000000000000),
 CHECK(instance_until IS NULL OR instance_until<=8640000000000000),
 CHECK((probe_instance='current-registered' AND instance_until IS NOT NULL)
    OR (probe_instance='not-rechecked' AND instance_until IS NULL)),
 CHECK(recovery_suspended IN (0,1)),
 CHECK(mapping_source IN ('published-snapshot')),
 CHECK(OCTET_LENGTH(body)<=4096),
 CHECK(OCTET_LENGTH(exporter)<=2048)
);
