-- Independent notification outbox; no execution authority or destination credentials.
CREATE TABLE notification_delivery_scopes (
 scope_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 queue_rejected BIGINT UNSIGNED NOT NULL DEFAULT 0,
 routing_rejected BIGINT UNSIGNED NOT NULL DEFAULT 0,
 silence_suppressed BIGINT UNSIGNED NOT NULL DEFAULT 0,
 disabled_suppressed BIGINT UNSIGNED NOT NULL DEFAULT 0,
 rows_expired BIGINT UNSIGNED NOT NULL DEFAULT 0,
 rows_evicted BIGINT UNSIGNED NOT NULL DEFAULT 0,
 attempts_evicted BIGINT UNSIGNED NOT NULL DEFAULT 0,
 FOREIGN KEY(scope_id) REFERENCES scopes(id),
 CHECK(queue_rejected<=9007199254740991 AND routing_rejected<=9007199254740991),
 CHECK(silence_suppressed<=9007199254740991 AND disabled_suppressed<=9007199254740991),
 CHECK(rows_expired<=9007199254740991 AND rows_evicted<=9007199254740991 AND attempts_evicted<=9007199254740991)
);
CREATE TABLE notification_deliveries (
 id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 scope_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 event_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 policy_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 endpoint_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 policy_config_revision BIGINT UNSIGNED NOT NULL,
 endpoint_revision BIGINT UNSIGNED NOT NULL,
 credential_revision BIGINT UNSIGNED NOT NULL,
 policy_managed_by VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 endpoint_managed_by VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 authority_digest CHAR(71) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 payload JSON NOT NULL,
 payload_digest CHAR(71) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 revision BIGINT UNSIGNED NOT NULL,
 status ENUM('queued','claimed','retry-wait','delivered','dead-letter','cancelled') NOT NULL,
 attempt_count BIGINT UNSIGNED NOT NULL,
 fence BIGINT UNSIGNED NOT NULL,
 claimed_at BIGINT UNSIGNED NULL,
 claim_until BIGINT UNSIGNED NULL,
 created_at BIGINT UNSIGNED NOT NULL,
 updated_at BIGINT UNSIGNED NOT NULL,
 next_attempt_at BIGINT UNSIGNED NOT NULL,
 expires_at BIGINT UNSIGNED NOT NULL,
 last_code VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
 last_outcome ENUM('none','delivered','rejected','unknown') NOT NULL,
 last_status_code INT UNSIGNED NULL,
 recovery_suspended BOOLEAN NOT NULL DEFAULT FALSE,
 UNIQUE KEY notification_delivery_scope_id(scope_id,id),
 UNIQUE KEY notification_delivery_event_endpoint(scope_id,event_id,endpoint_id),
 INDEX notification_delivery_due(status,next_attempt_at,id),
 INDEX notification_delivery_window(scope_id,created_at,id),
 INDEX notification_delivery_endpoint_window(scope_id,endpoint_id,created_at,id),
 INDEX notification_delivery_terminal(scope_id,status,created_at,id),
 INDEX notification_delivery_active(scope_id,status,claim_until),
 FOREIGN KEY(scope_id) REFERENCES notification_delivery_scopes(scope_id),
 FOREIGN KEY(scope_id,endpoint_id) REFERENCES notification_endpoints(scope_id,endpoint_id),
 CHECK(policy_config_revision BETWEEN 1 AND 9007199254740991),
 CHECK(endpoint_revision BETWEEN 1 AND 9007199254740991),
 CHECK(credential_revision BETWEEN 1 AND endpoint_revision),
 CHECK(JSON_TYPE(payload)='OBJECT' AND OCTET_LENGTH(payload)<=4096),
 CHECK(revision BETWEEN 1 AND 9007199254740991),
 CHECK(attempt_count<=6 AND fence=attempt_count),
 CHECK(created_at<=9007199254740991 AND updated_at<=9007199254740991),
 CHECK(next_attempt_at<=9007199254740991 AND expires_at<=9007199254740991),
 CHECK(expires_at=created_at+3600000 AND updated_at>=created_at),
 CHECK(claimed_at IS NULL OR claimed_at<=9007199254740991),
 CHECK(claim_until IS NULL OR claim_until<=9007199254740991),
 CHECK((status='claimed' AND claimed_at IS NOT NULL AND claim_until IS NOT NULL AND claim_until>claimed_at)
    OR (status<>'claimed' AND claimed_at IS NULL AND claim_until IS NULL)),
 CHECK(status<>'claimed' OR (attempt_count>=1 AND claim_until=claimed_at+30000 AND claimed_at>=created_at AND next_attempt_at>=claim_until)),
 CHECK((status IN ('delivered','dead-letter','cancelled') AND next_attempt_at=0)
    OR (status IN ('queued','retry-wait','claimed') AND next_attempt_at>=created_at)),
 CHECK(last_status_code IS NULL OR last_status_code BETWEEN 100 AND 599),
 CHECK(recovery_suspended IN (0,1))
);
CREATE TABLE notification_delivery_attempts (
 id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 scope_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 delivery_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 ordinal BIGINT UNSIGNED NOT NULL,
 fence BIGINT UNSIGNED NOT NULL,
 started_at BIGINT UNSIGNED NOT NULL,
 finished_at BIGINT UNSIGNED NULL,
 outcome ENUM('pending','delivered','rejected','unknown') NOT NULL,
 code VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
 status_code INT UNSIGNED NULL,
 UNIQUE KEY notification_attempt_fence(scope_id,delivery_id,fence),
 UNIQUE KEY notification_attempt_ordinal(scope_id,delivery_id,ordinal),
 INDEX notification_attempt_scope_window(scope_id,started_at,id),
 FOREIGN KEY(scope_id,delivery_id) REFERENCES notification_deliveries(scope_id,id),
 CHECK(ordinal BETWEEN 1 AND 6),
 CHECK(fence=ordinal),
 CHECK(started_at<=9007199254740991),
 CHECK(finished_at IS NULL OR finished_at BETWEEN started_at AND 9007199254740991),
 CHECK((outcome='pending' AND finished_at IS NULL) OR (outcome<>'pending' AND finished_at IS NOT NULL)),
 CHECK(status_code IS NULL OR status_code BETWEEN 100 AND 599)
);
CREATE TABLE notification_delivery_rates (
 scope_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 endpoint_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 next_allowed_at BIGINT UNSIGNED NOT NULL,
 PRIMARY KEY(scope_id,endpoint_id),
 FOREIGN KEY(scope_id) REFERENCES notification_delivery_scopes(scope_id),
 FOREIGN KEY(scope_id,endpoint_id) REFERENCES notification_endpoints(scope_id,endpoint_id),
 CHECK(next_allowed_at<=9007199254740991)
);
