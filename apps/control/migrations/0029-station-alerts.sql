-- Control-owned sampled station alerts, independent of execution authority.
CREATE TABLE station_alert_scopes (
 scope_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 events_evicted BIGINT UNSIGNED NOT NULL DEFAULT 0,
 events_expired BIGINT UNSIGNED NOT NULL DEFAULT 0,
 audit_evicted BIGINT UNSIGNED NOT NULL DEFAULT 0,
 FOREIGN KEY(scope_id) REFERENCES scopes(id),
 CHECK(events_evicted<=9007199254740991),
 CHECK(events_expired<=9007199254740991),
 CHECK(audit_evicted<=9007199254740991)
);
CREATE TABLE station_alert_policies (
 scope_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 policy_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 revision BIGINT UNSIGNED NOT NULL,
 config_revision BIGINT UNSIGNED NOT NULL,
 config_digest CHAR(71) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 config JSON NOT NULL,
 enabled BOOLEAN NOT NULL,
 managed_by VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 created_at BIGINT UNSIGNED NOT NULL,
 updated_at BIGINT UNSIGNED NOT NULL,
 silenced_until BIGINT UNSIGNED NULL,
 suspended ENUM('none','recovery','actor-not-authorized') NOT NULL,
 next_evaluate_at BIGINT UNSIGNED NOT NULL,
 state JSON NOT NULL,
 PRIMARY KEY(scope_id,policy_id),
 INDEX station_alert_due(enabled,suspended,next_evaluate_at,scope_id,policy_id),
 FOREIGN KEY(scope_id) REFERENCES station_alert_scopes(scope_id),
 FOREIGN KEY(managed_by) REFERENCES accounts(id),
 CHECK(revision BETWEEN 1 AND 9007199254740991),
 CHECK(config_revision BETWEEN 1 AND revision),
 CHECK(enabled IN (0,1)),
 CHECK(JSON_TYPE(config)='OBJECT' AND OCTET_LENGTH(config)<=1024),
 CHECK(JSON_EXTRACT(config,'$.enabled') IS NOT NULL AND JSON_TYPE(JSON_EXTRACT(config,'$.enabled'))='BOOLEAN'),
 CHECK(enabled=(JSON_EXTRACT(config,'$.enabled')=CAST('true' AS JSON))),
 CHECK(JSON_TYPE(state)='OBJECT' AND OCTET_LENGTH(state)<=8192),
 CHECK(created_at<=9007199254740991 AND updated_at<=9007199254740991),
 CHECK(silenced_until IS NULL OR silenced_until<=9007199254740991),
 CHECK(next_evaluate_at<=9007199254740991)
);
CREATE TABLE station_alert_events (
 id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 scope_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 policy_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 occurred_at BIGINT UNSIGNED NOT NULL,
 rule ENUM('forward-operation-failed','node-report-stale','node-credential-expiring') NOT NULL,
 target_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 kind ENUM('firing','recovered','invalidated') NOT NULL,
 episode BIGINT UNSIGNED NOT NULL,
 config_revision BIGINT UNSIGNED NOT NULL,
 body JSON NOT NULL,
 revision BIGINT UNSIGNED NOT NULL,
 acknowledged_at BIGINT UNSIGNED NULL,
 recovery_suspended BOOLEAN NOT NULL DEFAULT FALSE,
 UNIQUE KEY station_alert_transition(scope_id,policy_id,config_revision,episode,kind),
 INDEX station_alert_window(scope_id,occurred_at,id),
 INDEX station_alert_policy_window(scope_id,policy_id,occurred_at,id),
 FOREIGN KEY(scope_id,policy_id) REFERENCES station_alert_policies(scope_id,policy_id),
 CHECK(occurred_at<=9007199254740991),
 CHECK(episode BETWEEN 1 AND 9007199254740991),
 CHECK(config_revision BETWEEN 1 AND 9007199254740991),
 CHECK(revision BETWEEN 1 AND 9007199254740991),
 CHECK(acknowledged_at IS NULL OR acknowledged_at<=9007199254740991),
 CHECK(recovery_suspended IN (0,1)),
 CHECK(JSON_TYPE(body)='OBJECT' AND OCTET_LENGTH(body)<=4096)
);
CREATE TABLE station_alert_policy_events (
 id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin PRIMARY KEY,
 scope_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 policy_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 revision BIGINT UNSIGNED NOT NULL,
 config_revision BIGINT UNSIGNED NOT NULL,
 config_digest CHAR(71) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 kind ENUM('publish','silence','acknowledge') NOT NULL,
 actor_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 created_at BIGINT UNSIGNED NOT NULL,
 event_id VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NULL,
 INDEX station_alert_audit_scope(scope_id,created_at,id),
 INDEX station_alert_audit_policy(scope_id,policy_id,created_at,id),
 FOREIGN KEY(scope_id,policy_id) REFERENCES station_alert_policies(scope_id,policy_id),
 FOREIGN KEY(actor_id) REFERENCES accounts(id),
 CHECK(revision BETWEEN 1 AND 9007199254740991),
 CHECK(config_revision BETWEEN 1 AND 9007199254740991),
 CHECK(kind='acknowledge' OR config_revision<=revision),
 CHECK(created_at<=9007199254740991)
);
