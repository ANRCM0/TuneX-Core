window.runRoutingFixtureChecks = async function () {
  const evidence = [], pause = (ms = 30) => new Promise((done) => setTimeout(done, ms));
  function check(condition, name) { if (!condition) throw new Error(name); evidence.push(name); }
  async function until(read, name) { for (let i = 0; i < 250; i++) { if (read()) return; await pause(); } throw new Error(name); }
  const buttons = () => [...document.querySelectorAll('button')];
  const button = (text) => buttons().find((el) => el.textContent === text);
  await until(() => button('Preview candidates'), 'authorized route choices load');
  check(button('Save policy').disabled, 'save requires a preview');
  check(document.body.textContent.includes('Automatic execution is disabled'), 'platform default-off is explained');
  const inputs = [...document.querySelectorAll('[data-testid=forward-routing-card] input[type=checkbox]')];
  inputs[1].click();
  button('Preview candidates').click();
  await until(() => !button('Save policy').disabled, 'preview validates both selected paths');
  button('Save policy').click();
  await until(() => document.body.textContent.includes('Policy saved.'), 'saved policy receipt');
  const state = (await (await fetch('/__test/state')).json()).data;
  const save = state.calls.find((c) => c.method === 'PUT');
  check(save.workspaceId === 5 && save.body.expected_policy_version === 0, 'write captures workspace and optimistic version');
  check(save.body.intent.candidates.length === 2 && save.body.intent.expected_revision === 5, 'write preserves two paths and exact business revision');
  check(!save.body.enabled && !save.body.auto_failover && !save.body.auto_failback, 'automation defaults remain off');
  button('Refresh').click();
  await until(() => document.body.textContent.includes('no_qualified_path'), 'fresh decision explains missing observations');
  check(document.querySelector('[data-testid=routing-history]').textContent.includes('pending'), 'pending receipt is not confirmed');
  check(document.querySelector('[data-testid=routing-history]').textContent.includes('5 / 6 / ?'), 'unknown ACK remains explicit');
  button('Toggle reader').click();
  await until(() => button('Preview candidates').disabled, 'reader action gates update');
  check(button('Preview candidates').disabled && button('Probe authorized target').disabled, 'reader cannot probe or alter policies');
  button('Toggle reader').click();
  await until(() => !button('Preview candidates').disabled, 'writer action gates restore');
  button('Enable conflict').click();
  await pause(100);
  await until(() => button('Preview candidates') && !button('Preview candidates').disabled, 'conflict fixture reload');
  button('Preview candidates').click(); await until(() => !button('Save policy').disabled, 'conflict preview');
  button('Save policy').click(); await until(() => document.body.textContent.includes('policy_version_conflict'), 'conflict stays visible without silent rebasing');
  button('Delay reads').click(); await pause(80); button('Switch workspace').click();
  await until(() => document.body.textContent.includes('forward_not_found'), 'foreign forward is denied');
  await pause(1300);
  check(!document.body.textContent.includes('Fixture node 1') && !document.body.textContent.includes('no_qualified_path'), 'late old-workspace reads cannot repopulate scoped data');
  button('Switch workspace').click();
  await until(() => button('Preview candidates'), 'original workspace restored');
  button('Disable routing').click();
  await until(() => document.body.textContent.includes('Advanced routing is disabled by the platform.'), 'disabled platform discovered without topology writes');
  return { method: 'real_isolated_chromium_http_fixture', pass: evidence.length, evidence };
};
