  PRIMARY KEY (`id`),
  CONSTRAINT `routing_policy_workspace_id_fkey` FOREIGN KEY (`workspace_id`) REFERENCES `workspace` (`id`) ON DELETE CASCADE ON UPDATE CASCADE,
