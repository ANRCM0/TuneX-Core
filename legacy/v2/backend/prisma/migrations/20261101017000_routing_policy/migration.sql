CREATE TABLE `routing_policy` (
  `id` INTEGER NOT NULL AUTO_INCREMENT,
  `workspace_id` INTEGER NOT NULL,
  `forward_id` INTEGER NOT NULL,
  `version` INTEGER NOT NULL DEFAULT 1,
  `state_version` INTEGER NOT NULL DEFAULT 0,
  `created_by_id` INTEGER NOT NULL,
  `forward_revision` INTEGER NOT NULL,
  `authority_digest` CHAR(64) NOT NULL,
  `enabled` BOOLEAN NOT NULL DEFAULT false,
  `intent` JSON NOT NULL,
  `controller_state` JSON NOT NULL,
  `last_decision` JSON NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL,
  UNIQUE INDEX `routing_policy_forward_id_key` (`forward_id`),
